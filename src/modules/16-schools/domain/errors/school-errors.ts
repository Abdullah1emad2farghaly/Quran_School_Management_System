import { AppError, type ErrorKind } from '../../../00-shared-kernel/public';

export const SchoolErrorCodes = {
  INVALID_SCHOOL_NAME: 'INVALID_SCHOOL_NAME',
  INVALID_GPS_COORDINATES: 'INVALID_GPS_COORDINATES',
  /** The reported GPS accuracy is worse than 20 metres (§30). No manual or IP fallback exists. */
  GPS_ACCURACY_EXCEEDS_LIMIT: 'GPS_ACCURACY_EXCEEDS_LIMIT',
  INVALID_REJECTION_REASON: 'INVALID_REJECTION_REASON',
  SCHOOL_NOT_FOUND: 'SCHOOL_NOT_FOUND',
  /** Names are unique per organization (REJECTED requests do not hold their name). */
  SCHOOL_NAME_ALREADY_EXISTS: 'SCHOOL_NAME_ALREADY_EXISTS',
  SCHOOL_ORGANIZATION_INACTIVE: 'SCHOOL_ORGANIZATION_INACTIVE',
  SCHOOL_INVALID_STATUS_TRANSITION: 'SCHOOL_INVALID_STATUS_TRANSITION',
  /** Official GPS can be corrected only while the school is PENDING; after approval it is immutable in V1. */
  SCHOOL_GPS_LOCKED: 'SCHOOL_GPS_LOCKED',
  /** The user is missing, not ACTIVE, or cannot be given the SCHOOL_MANAGER role. */
  SCHOOL_MANAGER_NOT_ELIGIBLE: 'SCHOOL_MANAGER_NOT_ELIGIBLE',
  SCHOOL_NOT_ACTIVE: 'SCHOOL_NOT_ACTIVE',
  SCHOOL_ALREADY_HAS_MANAGER: 'SCHOOL_ALREADY_HAS_MANAGER',
  SCHOOL_MANAGER_ASSIGNMENT_NOT_FOUND: 'SCHOOL_MANAGER_ASSIGNMENT_NOT_FOUND',
  SCHOOL_CONCURRENT_MODIFICATION: 'SCHOOL_CONCURRENT_MODIFICATION',
  /** The school's country must be its organization's country (derived server-side; a conflicting country is refused). */
  SCHOOL_COUNTRY_MISMATCH: 'SCHOOL_COUNTRY_MISMATCH',
  INVALID_APPLICANT_NAME: 'INVALID_APPLICANT_NAME',
  /** A logged-in applicant submitted a phone number that is not the phone of their own account. */
  SCHOOL_APPLICANT_IDENTITY_MISMATCH: 'SCHOOL_APPLICANT_IDENTITY_MISMATCH',
} as const;
export type SchoolErrorCode = (typeof SchoolErrorCodes)[keyof typeof SchoolErrorCodes];

const KIND: Record<SchoolErrorCode, ErrorKind> = {
  INVALID_SCHOOL_NAME: 'VALIDATION',
  INVALID_GPS_COORDINATES: 'VALIDATION',
  GPS_ACCURACY_EXCEEDS_LIMIT: 'VALIDATION',
  INVALID_REJECTION_REASON: 'VALIDATION',
  SCHOOL_NOT_FOUND: 'NOT_FOUND',
  SCHOOL_NAME_ALREADY_EXISTS: 'CONFLICT',
  SCHOOL_ORGANIZATION_INACTIVE: 'BUSINESS_RULE',
  SCHOOL_INVALID_STATUS_TRANSITION: 'BUSINESS_RULE',
  SCHOOL_GPS_LOCKED: 'BUSINESS_RULE',
  SCHOOL_MANAGER_NOT_ELIGIBLE: 'BUSINESS_RULE',
  SCHOOL_NOT_ACTIVE: 'BUSINESS_RULE',
  SCHOOL_ALREADY_HAS_MANAGER: 'CONFLICT',
  SCHOOL_MANAGER_ASSIGNMENT_NOT_FOUND: 'NOT_FOUND',
  SCHOOL_CONCURRENT_MODIFICATION: 'CONFLICT',
  SCHOOL_COUNTRY_MISMATCH: 'VALIDATION',
  INVALID_APPLICANT_NAME: 'VALIDATION',
  SCHOOL_APPLICANT_IDENTITY_MISMATCH: 'CONFLICT',
};

export function schoolError(code: SchoolErrorCode): AppError {
  return new AppError(code, KIND[code]);
}

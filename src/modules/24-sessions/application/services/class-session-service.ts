import { SystemClock, buildPageResult, businessDateOf, type Clock, type PageRequest, type PageResult, type TransactionContext, type UnitOfWork } from '../../../00-shared-kernel/public';
import type { OutboxService } from '../../../06-domain-events-outbox/public';
import type { TeacherLookup } from '../../../18-teachers/public';
import { isoNumberOf, parseMinutes, type ActiveSlotDto, type GroupScheduleService } from '../../../23-group-schedules/public';
import { ClassSession } from '../../domain/entities/class-session';
import { classSessionError } from '../../domain/errors/session-errors';
import { addDays, cairoWallClockToUtc, isoWeekdayOfDate } from '../../domain/value-objects/cairo-time';
import { SESSION_LEAD_MINUTES, SLOT_RETIREMENT_REASONS, type SessionStatus, type SlotRetirementReason } from '../../domain/value-objects/session-status';
import { toSessionDto, type ClassSessionDto } from '../dto/session-dto';
import type { ClassSessionRepository } from '../ports/session-repository';

export interface ClassSessionServiceDeps {
  readonly sessions: ClassSessionRepository;
  /** Module 23's public service, read-only here. */
  readonly schedule: Pick<GroupScheduleService, 'listActiveSlotsForSessions' | 'findSlotsByIds'>;
  readonly teachers: Pick<TeacherLookup, 'findByUserId'>;
  readonly unitOfWork: UnitOfWork;
  readonly outbox: OutboxService;
  readonly clock?: Clock;
}

export interface SessionListInput {
  readonly status?: readonly SessionStatus[];
  readonly direction?: 'asc' | 'desc';
  readonly page: PageRequest;
}

export interface CycleResult {
  /** Sessions cancelled because their slot was retired before the start. */
  readonly cancelledForRetiredSlots: number;
  readonly created: number;
  readonly started: number;
  readonly completed: number;
  /** Items that failed (each is retried at the next cycle). */
  readonly failed: number;
}

/** Sessions advanced per cycle at most (the rest is picked up by the next cycle). */
const MAX_ADVANCES_PER_CYCLE = 500;

/**
 * Public application contract of Module 24 (Class Sessions, Master Specification §45) and the approved Module 24 decisions of the project owner.
 *
 * It does NOT authorize its callers: routes use the Authorization Engine (`sessions.*` permissions) first. What it enforces itself:
 *  - NO GROUP SCHEDULE = NO SESSION: a session exists only as the occurrence of an ACTIVE schedule slot (Module 23). There is no way to create one by hand;
 *  - a session is generated by the system when its 15-minute threshold is reached (start - 15 minutes), already OPEN, one per slot occurrence (a unique
 *    (slot, date) index makes generation idempotent), and never days or weeks ahead. An occurrence qualifies only while it has not ended and only if the slot
 *    already existed at its threshold; a group without a Teacher has no session (a session belongs to a Teacher);
 *  - the system moves OPEN -> IN_PROGRESS at the scheduled start and IN_PROGRESS -> COMPLETED at the scheduled end; nobody triggers these by hand;
 *  - the assigned Teacher may cancel an OPEN or IN_PROGRESS session with a non-empty reason (actor, time and reason recorded); a COMPLETED session cannot be
 *    cancelled; sessions are never deleted;
 *  - when a slot is retired: a session that does not exist yet is never created; an OPEN session that has not started is cancelled automatically (source
 *    SCHEDULE_SLOT_RETIRED with the retirement reason); a started or completed session is left unchanged; an already cancelled session keeps its original reason and source;
 *  - every change publishes an outbox event in the same transaction. Nothing here creates, checks or changes teaching records (attendance, memorization, revision).
 */
export class ClassSessionService {
  private readonly sessions: ClassSessionRepository;
  private readonly schedule: ClassSessionServiceDeps['schedule'];
  private readonly teachers: ClassSessionServiceDeps['teachers'];
  private readonly unitOfWork: UnitOfWork;
  private readonly outbox: OutboxService;
  private readonly clock: Clock;

  constructor(deps: ClassSessionServiceDeps) {
    this.sessions = deps.sessions;
    this.schedule = deps.schedule;
    this.teachers = deps.teachers;
    this.unitOfWork = deps.unitOfWork;
    this.outbox = deps.outbox;
    this.clock = deps.clock ?? new SystemClock();
  }

  // ------------------------------------------------------------------------------------------ the system's work

  /** One pass of the background job: reconcile retired slots, generate due sessions, advance due sessions. A failure in one step never blocks the others. */
  async runCycle(): Promise<CycleResult> {
    let failed = 0;
    let cancelledForRetiredSlots = 0;
    let created = 0;
    let advanced = { started: 0, completed: 0, failed: 0 };
    try {
      cancelledForRetiredSlots = await this.reconcileRetiredSlots();
    } catch {
      failed += 1;
    }
    try {
      const generated = await this.generateDueSessions();
      created = generated.created;
      failed += generated.failed;
    } catch {
      failed += 1;
    }
    try {
      advanced = await this.advanceDueSessions();
    } catch {
      failed += 1;
    }
    return { cancelledForRetiredSlots, created, started: advanced.started, completed: advanced.completed, failed: failed + advanced.failed };
  }

  /**
   * Creates the session of every ACTIVE slot occurrence whose threshold (start - 15 minutes) has been reached and that has not ended. Each session is created in its own
   * transaction with its event; running again creates nothing twice.
   */
  async generateDueSessions(): Promise<{ created: number; failed: number }> {
    const now = this.clock.now();
    let created = 0;
    let failed = 0;
    for (const slot of await this.schedule.listActiveSlotsForSessions()) {
      for (const occurrence of this.dueOccurrences(slot, now)) {
        try {
          const inserted = await this.unitOfWork.run(async (tx) => {
            const session = ClassSession.open({
              schoolId: slot.schoolId,
              groupId: slot.groupId,
              teacherId: slot.teacherId as string,
              slotId: slot.id,
              occurrenceDate: occurrence.date,
              scheduledStart: occurrence.start,
              scheduledEnd: occurrence.end,
              clock: this.clock,
            });
            if (!(await this.sessions.insertIfAbsent(session, tx))) return false;
            await this.outbox.publishFrom(session, tx);
            return true;
          });
          if (inserted) created += 1;
        } catch {
          failed += 1;
        }
      }
    }
    return { created, failed };
  }

  /** Applies the automatic transitions that are due (start and end of a session), each session in its own transaction. */
  async advanceDueSessions(): Promise<{ started: number; completed: number; failed: number }> {
    const now = this.clock.now();
    let started = 0;
    let completed = 0;
    let failed = 0;
    for (const id of await this.sessions.listDueIds(now, MAX_ADVANCES_PER_CYCLE)) {
      try {
        const applied = await this.unitOfWork.run(async (tx) => {
          const session = await this.sessions.lockById(id, tx);
          if (!session) return [];
          const transitions = session.advance(this.clock);
          if (transitions.length > 0) {
            await this.sessions.save(session, tx);
            await this.outbox.publishFrom(session, tx);
          }
          return transitions;
        });
        if (applied.includes('STARTED')) started += 1;
        if (applied.includes('COMPLETED')) completed += 1;
      } catch {
        failed += 1;
      }
    }
    return { started, completed, failed };
  }

  /**
   * A schedule slot was retired (Module 23 event, or found retired by `reconcileRetiredSlots`): the OPEN sessions of that slot whose start was after the retirement are
   * cancelled by the system. Started, completed and already cancelled sessions are left exactly as they are. Idempotent. Returns how many were cancelled.
   */
  async cancelSessionsOfRetiredSlot(slotId: string, reason: string, retiredAt: Date): Promise<number> {
    if (!(SLOT_RETIREMENT_REASONS as readonly string[]).includes(reason)) return 0;
    return this.unitOfWork.run(async (tx) => {
      let cancelled = 0;
      for (const session of await this.sessions.lockOpenBySlot(slotId, tx)) {
        if (!session.cancelBecauseSlotRetired({ reason: reason as SlotRetirementReason, retiredAt, clock: this.clock })) continue;
        await this.sessions.save(session, tx);
        await this.outbox.publishFrom(session, tx);
        cancelled += 1;
      }
      return cancelled;
    });
  }

  /** Safety net for a missed or late event: finds OPEN sessions whose slot is retired now and cancels them as above. */
  async reconcileRetiredSlots(): Promise<number> {
    const slotIds = await this.sessions.listOpenSlotIds();
    if (slotIds.length === 0) return 0;
    let cancelled = 0;
    for (const slot of await this.schedule.findSlotsByIds(slotIds)) {
      if (slot.status !== 'RETIRED' || !slot.retiredAt || !slot.retireReason) continue;
      cancelled += await this.cancelSessionsOfRetiredSlot(slot.id, slot.retireReason, slot.retiredAt);
    }
    return cancelled;
  }

  // ------------------------------------------------------------------------------------------ the Teacher's action

  /**
   * The assigned Teacher cancels a session with a mandatory reason. Transitions due at this moment are applied first, so a session that has already reached
   * its end is COMPLETED and cannot be cancelled. The Teacher comes from the verified user id, never from the request.
   */
  async cancelSession(sessionId: string, userId: string, reason: unknown, tx?: TransactionContext): Promise<ClassSessionDto> {
    const teacher = await this.teachers.findByUserId(userId, tx);
    return this.write(tx, async (t) => {
      const session = await this.sessions.lockById(sessionId, t);
      if (!session) throw classSessionError('CLASS_SESSION_NOT_FOUND');
      if (!teacher || teacher.id !== session.snapshot.teacherId) throw classSessionError('CLASS_SESSION_NOT_ASSIGNED_TEACHER');
      session.advance(this.clock);
      session.cancelByTeacher({ teacherId: teacher.id, actorUserId: userId, reason, clock: this.clock });
      await this.sessions.save(session, t);
      await this.outbox.publishFrom(session, t);
      return toSessionDto(session);
    });
  }

  // ------------------------------------------------------------------------------------------ reads

  async getSession(sessionId: string, tx?: TransactionContext): Promise<ClassSessionDto> {
    const session = await this.sessions.findById(sessionId, tx);
    if (!session) throw classSessionError('CLASS_SESSION_NOT_FOUND');
    return toSessionDto(session);
  }

  /** The group of a session (the route authorizes against it). */
  async findGroupIdOf(sessionId: string, tx?: TransactionContext): Promise<string> {
    return (await this.getSession(sessionId, tx)).groupId;
  }

  async listGroupSessions(groupId: string, input: SessionListInput, tx?: TransactionContext): Promise<PageResult<ClassSessionDto>> {
    const { items, total } = await this.sessions.listByGroup(groupId, { status: input.status, direction: input.direction ?? 'desc' }, input.page, tx);
    return buildPageResult(items.map(toSessionDto), total, input.page);
  }

  /** The calling Teacher's own sessions (the Teacher record comes from the verified user id). */
  async listOwnSessions(userId: string, input: SessionListInput, tx?: TransactionContext): Promise<PageResult<ClassSessionDto>> {
    const teacher = await this.teachers.findByUserId(userId, tx);
    if (!teacher) return buildPageResult([], 0, input.page);
    const { items, total } = await this.sessions.listByTeacher(teacher.id, { status: input.status, direction: input.direction ?? 'desc' }, input.page, tx);
    return buildPageResult(items.map(toSessionDto), total, input.page);
  }

  // ------------------------------------------------------------------------------------------ internals

  /**
   * The occurrences of `slot` that qualify at `now`: the slot has a Teacher; the occurrence's threshold (start - 15 min) has been reached; it has not ended; and the
   * slot already existed at the threshold. Candidate dates are the business dates around `now`, which covers every zone offset.
   */
  private dueOccurrences(slot: ActiveSlotDto, now: Date): Array<{ date: string; start: Date; end: Date }> {
    if (!slot.teacherId) return [];
    const today = businessDateOf(now);
    const weekday = isoNumberOf(slot.dayOfWeek);
    const out: Array<{ date: string; start: Date; end: Date }> = [];
    for (const date of [addDays(today, -1), today, addDays(today, 1)]) {
      if (isoWeekdayOfDate(date) !== weekday) continue;
      const start = cairoWallClockToUtc(date, parseMinutes(slot.startTime));
      const end = cairoWallClockToUtc(date, parseMinutes(slot.endTime));
      const threshold = new Date(start.getTime() - SESSION_LEAD_MINUTES * 60_000);
      if (now >= threshold && now < end && slot.createdAt <= threshold) out.push({ date, start, end });
    }
    return out;
  }

  private write<T>(tx: TransactionContext | undefined, work: (tx: TransactionContext) => Promise<T>): Promise<T> {
    return tx ? work(tx) : this.unitOfWork.run(work);
  }
}

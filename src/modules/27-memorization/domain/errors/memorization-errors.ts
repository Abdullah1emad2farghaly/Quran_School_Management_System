  MEMORIZATION_STUDENT_REQUIRED: 'MEMORIZATION_STUDENT_REQUIRED',
  /** A GROUP-mode group has ONE shared assignment: an assignment for an individual student is refused. */
  MEMORIZATION_GROUP_ASSIGNMENT_NO_STUDENT: 'MEMORIZATION_GROUP_ASSIGNMENT_NO_STUDENT',
  MEMORIZATION_NOT_SESSION_TEACHER: 'MEMORIZATION_NOT_SESSION_TEACHER',
  MEMORIZATION_READ_NOT_ALLOWED: 'MEMORIZATION_READ_NOT_ALLOWED',
  MEMORIZATION_SESSION_CANCELLED: 'MEMORIZATION_SESSION_CANCELLED',
  /** The next-session assignment can be defined, modified or cancelled only while the current session is IN_PROGRESS. */
  MEMORIZATION_ASSIGNMENT_WINDOW_CLOSED: 'MEMORIZATION_ASSIGNMENT_WINDOW_CLOSED',
  MEMORIZATION_ASSIGNMENT_NOT_FOUND: 'MEMORIZATION_ASSIGNMENT_NOT_FOUND',
  MEMORIZATION_RECORD_NOT_FOUND: 'MEMORIZATION_RECORD_NOT_FOUND',
  MEMORIZATION_ASSIGNMENT_CANCELLED: 'MEMORIZATION_ASSIGNMENT_CANCELLED',
  MEMORIZATION_ASSIGNMENT_ALREADY_DEFINED: 'MEMORIZATION_ASSIGNMENT_ALREADY_DEFINED',
  /** A student who did not memorize the whole assigned range must repeat the ENTIRE original assignment (never only the unfinished part). */
  MEMORIZATION_REPEAT_REQUIRED: 'MEMORIZATION_REPEAT_REQUIRED',
  /** The record would not fulfil the assignment while a different next assignment is already defined for the student: change or cancel that one first. */
